
# 4. Use of various data types in Python
int_var = 10          # Integer
double_var = 10.5     # Floating point
str_var = "Hello"     # String
bool_var = True       # Boolean
list_var = [1, 2, 3]  # List
tuple_var = (4, 5, 6) # Tuple
dict_var = {"key": "value"} # Dictionary
set_var = {1, 2, 3}   # Set

print("Integer:", int_var)
print("Float:", double_var)
print("String:", str_var)
print("Boolean:", bool_var)
print("List:", list_var)
print("Tuple:", tuple_var)
print("Dictionary:", dict_var)
print("Set:", set_var)